"""Точкове доперекладення рядків, доданих разом із закупівельною ціною."""

import re
from pathlib import Path

PO = Path(__file__).resolve().parents[1] / "locale" / "ru" / "LC_MESSAGES" / "django.po"

TRANSLATIONS = {
    "Закупівельна ціна, грн": "Закупочная цена, грн",
    "Роздрібна ціна, грн": "Розничная цена, грн",
    "Порожньо — порахується автоматично від закупівельної плюс націнка.": (
        "Пусто — рассчитается автоматически от закупочной плюс наценка."
    ),
    "Роздрібна ціна вручну": "Розничная цена вручную",
    "Ціна косметолога вручну": "Цена косметолога вручную",
    "Закупівельна за одиницю": "Закупочная за единицу",
    "Графік роботи (укр)": "График работы (укр)",
    "Графік роботи (рос)": "График работы (рус)",
    "До копійки": "До копейки",
    "До гривні": "До гривны",
    "До 5 грн": "До 5 грн",
    "До 10 грн": "До 10 грн",
    "Націнка роздріб, %": "Наценка розница, %",
    "Націнка для косметологів, %": "Наценка для косметологов, %",
    "Роздрібна ціна = закупівельна + ця націнка.": "Розничная цена = закупочная + эта наценка.",
    "Ціна для косметологів = закупівельна + ця націнка.": (
        "Цена для косметологов = закупочная + эта наценка."
    ),
    "Округлення цін": "Округление цен",
    "Контакти і реквізити": "Контакты и реквизиты",
    "Службове поле, на сайті не показується. Від нього рахуються інші ціни.": (
        "Служебное поле, на сайте не показывается. От него считаются другие цены."
    ),
    "Увімкніть, щоб автоперерахунок не перезаписував цю ціну.": (
        "Включите, чтобы автопересчёт не перезаписывал эту цену."
    ),
}


def main() -> None:
    text = PO.read_text(encoding="utf-8")
    blocks = text.split("\n\n")
    changed = 0

    for index, block in enumerate(blocks):
        match = re.search(r'^msgid "(.+?)"$', block, re.M)
        if not match or match.group(1) not in TRANSLATIONS:
            continue

        updated = re.sub(
            r'^msgstr ".*?"$',
            'msgstr "{}"'.format(TRANSLATIONS[match.group(1)]),
            block,
            count=1,
            flags=re.M,
        )
        updated = "\n".join(
            line
            for line in updated.splitlines()
            if line != "#, fuzzy" and not line.startswith("#| msgid")
        )
        if updated != block:
            blocks[index] = updated
            changed += 1

    PO.write_text("\n\n".join(blocks), encoding="utf-8")
    print(f"Оновлено рядків: {changed}")


if __name__ == "__main__":
    main()
